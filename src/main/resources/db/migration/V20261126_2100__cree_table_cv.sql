CREATE TABLE cv (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    titre VARCHAR(120) NOT NULL,
    langue VARCHAR(2) NOT NULL CHECK (langue IN ('FR', 'EN')),
    modele VARCHAR(20) NOT NULL CHECK (modele IN ('CLASSIQUE', 'MODERNE', 'COMPACT')),
    police VARCHAR(30) NOT NULL CHECK (police IN ('INTER', 'LATO', 'IBM_PLEX_SANS', 'SOURCE_SERIF_4', 'LORA')),
    contenu JSONB NOT NULL,
    date_creation TIMESTAMP WITH TIME ZONE NOT NULL,
    date_modification TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_cv_utilisateur_id ON cv (utilisateur_id);
