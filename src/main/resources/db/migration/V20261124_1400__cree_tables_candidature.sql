-- Suivi des candidatures : candidature + fiche de préparation à l'entretien (IA)

CREATE TABLE candidature (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id      BIGINT        NOT NULL
        REFERENCES utilisateur (id) ON DELETE CASCADE,
    intitule            VARCHAR(200)  NOT NULL,
    entreprise          VARCHAR(200)  NOT NULL,
    lieu                VARCHAR(200),
    url_offre           VARCHAR(1000),
    description_offre   VARCHAR(10000),
    statut              VARCHAR(30)   NOT NULL
        CHECK (statut IN ('EN_ATTENTE', 'ENTRETIEN', 'REFUSEE')),
    date_candidature    DATE          NOT NULL,
    date_entretien      DATE,
    date_dernier_statut TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_candidature_utilisateur_statut ON candidature (utilisateur_id, statut);

CREATE TABLE preparation_entretien (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id   BIGINT        NOT NULL UNIQUE
        REFERENCES candidature (id) ON DELETE CASCADE,
    contenu          VARCHAR(30000) NOT NULL,
    generee_le       TIMESTAMP WITH TIME ZONE NOT NULL,
    modele           VARCHAR(100)  NOT NULL
);
