-- Offres d'emploi, de stage ou d'alternance, venant d'une API (France Travail) ou importées depuis un lien.
-- Une offre est la même pour tous les candidats : elle n'appartient à personne (voir tri_offre).
CREATE TABLE offre (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source           VARCHAR(30)              NOT NULL,
    -- Identifiant de l'offre dans sa source : identifiant France Travail, ou URL pour un import par lien
    id_externe       VARCHAR(2048)            NOT NULL,
    url              VARCHAR(2048),
    titre            VARCHAR(255)             NOT NULL,
    entreprise       VARCHAR(255),
    lieu             VARCHAR(255),
    type_contrat     VARCHAR(100),
    description      TEXT,
    date_publication DATE,
    date_import      TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT ck_offre_source CHECK (source IN ('FRANCE_TRAVAIL', 'LIEN')),
    -- Empêche d'importer deux fois la même offre
    CONSTRAINT uk_offre_source_id_externe UNIQUE (source, id_externe)
);
