-- Choix de chaque candidat sur une offre : il la garde ou il la passe.
CREATE TABLE tri_offre (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Pas encore de clé étrangère : la table utilisateur arrive avec l'authentification (socle).
    -- Une migration ajoutera la contrainte vers utilisateur(id) à ce moment-là.
    utilisateur_id BIGINT                   NOT NULL,
    offre_id       BIGINT                   NOT NULL,
    choix          VARCHAR(10)              NOT NULL,
    date_choix     TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_tri_offre_offre FOREIGN KEY (offre_id) REFERENCES offre (id) ON DELETE CASCADE,
    CONSTRAINT ck_tri_offre_choix CHECK (choix IN ('GARDEE', 'PASSEE')),
    -- Un seul choix par candidat et par offre ; changer d'avis met à jour la ligne existante
    CONSTRAINT uk_tri_offre_utilisateur_offre UNIQUE (utilisateur_id, offre_id)
);

CREATE INDEX ix_tri_offre_utilisateur ON tri_offre (utilisateur_id);
